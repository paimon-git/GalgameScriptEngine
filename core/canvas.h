#pragma once

// ---------------------------------------------------------------------------
// 画布缩放
//
// 游戏按固定的「设计分辨率」（默认 1280x720）排版，窗口可以是任意大小：
// 每帧算出等比缩放系数，把整块画布居中铺到窗口里，多出来的部分留黑边。
// 这样在 4K 屏上放大会整体变大，而不是只把控件拉开、字还那么小。
//
// 注意：场景里的排版尺寸要取 canvas::width()/height()（设计分辨率），
// 不要用 raylib 的 GetScreenWidth()（那是真实窗口尺寸）。
// ---------------------------------------------------------------------------

namespace canvas
{
// 设定设计分辨率（只影响排版基准，不改窗口）
void setDesign(int w, int h);

int width();      // 设计分辨率宽
int height();     // 设计分辨率高
float scale();    // 设计坐标 -> 窗口坐标的缩放系数
float offsetX();  // 画布左上角在窗口中的位置（黑边宽度）
float offsetY();

// 每帧调用一次：按当前窗口大小重算缩放 / 黑边，并同步鼠标坐标映射，
// 使 GetMousePosition() 返回的仍是设计坐标。
void update();
}
